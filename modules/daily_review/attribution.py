def match_rules(news_text: str) -> List[Dict[str, Any]]:
    """根据新闻标题/内容匹配影响规则，返回命中的规则列表。"""
    if not news_text:
        return []
    text = str(news_text)
    matched = []
    for rule in RULES:
        for kw in rule["keywords"]:
            if kw in text:
                matched.append(rule)
                break
    return matched


def analyze_news_attribution(
    news: List[Dict[str, Any]],
    sectors_all: Dict[str, float],
) -> List[Dict[str, Any]]:
    """
    对每条新闻做归因分析，返回结构化结果。

    返回每条新闻的：
    - news: 原新闻
    - rules: 命中的规则
    - impacts: 受影响板块列表，每项含 (板块名, 方向, 实际涨跌, 逻辑, 是否验证)
    """
    results = []
    for n in news:
        title = n.get("title", "") or ""
        content = n.get("content", "") or ""
        text = title + " " + content
        rules = match_rules(text)
        if not rules:
            continue

        impacts = []
        seen_sectors = set()
        for rule in rules:
            for sector_name, direction, chain in rule["sectors"]:
                if sector_name in seen_sectors:
                    continue
                seen_sectors.add(sector_name)
                # 查找该板块当日实际涨跌
                actual = sectors_all.get(sector_name)
                if actual is None:
                    # 模糊匹配：板块名可能不完全一致
                    actual = _fuzzy_find_sector(sector_name, sectors_all)
                verified = None
                if actual is not None:
                    if direction == 1:
                        verified = actual > 0
                    elif direction == -1:
                        verified = actual < 0
                impacts.append({
                    "sector": sector_name,
                    "direction": direction,  # 1利好 -1利空
                    "chain": chain,
                    "actual": actual,
                    "verified": verified,  # True实际方向一致 / False不一致 / None无数据
                    "rule_name": rule["name"],
                    "rule_logic": rule["logic"],
                })
        results.append({"news": n, "rules": rules, "impacts": impacts})
    return results


def _fuzzy_find_sector(name: str, sectors_all: Dict[str, float]) -> float:
    """板块名模糊匹配（新浪行业名与规则名可能有细微差异）。"""
    if not name:
        return None
    # 完全包含匹配
    for sn, val in sectors_all.items():
        if name in sn or sn in name:
            return val
    # 取前2字模糊匹配
    if len(name) >= 2:
        prefix = name[:2]
        for sn, val in sectors_all.items():
            if sn.startswith(prefix):
                return val
    return None
